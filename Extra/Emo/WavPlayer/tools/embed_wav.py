#!/usr/bin/env python3
"""Embed a PCM WAV file in an Arduino header for WavPlayer."""

import argparse
import pathlib
import wave


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("wav", type=pathlib.Path, help="input PCM WAV file")
    parser.add_argument(
        "output",
        type=pathlib.Path,
        nargs="?",
        default=pathlib.Path(__file__).resolve().parents[1] / "audio_data.h",
        help="output header (default: WavPlayer/audio_data.h)",
    )
    args = parser.parse_args()

    try:
        with wave.open(str(args.wav), "rb") as wav:
            channels = wav.getnchannels()
            sample_rate = wav.getframerate()
            sample_width = wav.getsampwidth()
            frames = wav.getnframes()
            compression = wav.getcomptype()
    except (OSError, EOFError, wave.Error) as exc:
        parser.error(f"cannot read WAV file: {exc}")

    if compression != "NONE":
        parser.error("only uncompressed PCM WAV files are supported")
    if channels not in (1, 2):
        parser.error("WAV must be mono or stereo")
    if sample_width not in (1, 2, 3, 4):
        parser.error("WAV samples must be 8-, 16-, 24-, or 32-bit PCM")
    if not 8000 <= sample_rate <= 96000:
        parser.error("sample rate must be between 8000 and 96000 Hz")
    if frames == 0:
        parser.error("WAV file contains no audio frames")

    data = args.wav.read_bytes()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Generated by tools/embed_wav.py - do not edit",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "const uint8_t audioData[] PROGMEM = {",
    ]
    for start in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{byte:02X}" for byte in data[start : start + 16]) + ",")
    lines.extend(
        [
            "};",
            f"const uint32_t audioDataSize = {len(data)};",
            "",
        ]
    )
    args.output.write_text("\n".join(lines), encoding="ascii")
    print(
        f"Embedded {args.wav} ({frames / sample_rate:.2f}s, "
        f"{sample_rate} Hz, {channels} ch, {sample_width * 8}-bit) "
        f"into {args.output} ({len(data)} bytes)"
    )


if __name__ == "__main__":
    main()
