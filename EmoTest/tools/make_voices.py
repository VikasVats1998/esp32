#!/usr/bin/env python3
"""Convert WAV voice clips into voices.h (16-bit mono C arrays).

usage: make_voices.py OUT_HEADER PITCH [--rate N] name1=file1.wav name2=file2.wav ...
PITCH > 1 makes the voice higher and faster (cute robot), 1.0 = natural.
--rate sets the output sample rate (default: same as the input, best quality).
"""
import math
import struct
import sys
import wave


def load(path):
    with wave.open(path, "rb") as w:
        assert w.getsampwidth() == 2, "need 16-bit wav"
        ch, rate, n = w.getnchannels(), w.getframerate(), w.getnframes()
        data = struct.unpack("<%dh" % (n * ch), w.readframes(n))
    return list(data[::ch]), rate


def lowpass(s, cutoff_ratio):
    """Windowed-sinc low-pass so downsampling does not alias (fuzzy/harsh sound)."""
    taps = 31
    m = taps // 2
    k = []
    for i in range(taps):
        x = i - m
        sinc = 2 * cutoff_ratio if x == 0 else math.sin(2 * math.pi * cutoff_ratio * x) / (math.pi * x)
        k.append(sinc * (0.54 - 0.46 * math.cos(2 * math.pi * i / (taps - 1))))
    total = sum(k)
    k = [v / total for v in k]
    out = []
    for i in range(len(s)):
        acc = 0.0
        for j in range(taps):
            idx = i + j - m
            if 0 <= idx < len(s):
                acc += s[idx] * k[j]
        out.append(acc)
    return out


def resample(s, src_rate, dst_rate, pitch):
    step = src_rate * pitch / dst_rate
    if abs(step - 1) < 1e-9:
        return [float(v) for v in s]
    if step > 1:
        s = lowpass(s, 0.45 / step)
    out, pos = [], 0.0
    while pos < len(s) - 1:
        i = int(pos)
        f = pos - i
        out.append(s[i] * (1 - f) + s[i + 1] * f)
        pos += step
    return out


def trim(s, rate, thresh=300):
    idx = [i for i, v in enumerate(s) if abs(v) > thresh]
    if not idx:
        return s
    s = s[max(0, idx[0] - rate // 100): idx[-1] + rate // 40]
    fade = rate // 200  # 5 ms fade in/out to avoid clicks
    for i in range(min(fade, len(s))):
        g = i / fade
        s[i] *= g
        s[-1 - i] *= g
    return s


def main():
    args = sys.argv[1:]
    out_path, pitch = args[0], float(args[1])
    rest = args[2:]
    rate = None
    if rest and rest[0] == "--rate":
        rate = int(rest[1])
        rest = rest[2:]

    clips = []
    for arg in rest:
        name, path = arg.split("=", 1)
        s, src_rate = load(path)
        if rate is None:
            rate = src_rate
        s = trim(resample(s, src_rate, rate, pitch), rate)
        peak = max(1, max(abs(v) for v in s))
        clips.append((name, [int(round(v * 29000 / peak)) for v in s]))
        print("%-12s %.2fs @ %d Hz" % (name, len(clips[-1][1]) / rate, rate))

    lines = ["// Generated by tools/make_voices.py - do not edit", "#pragma once", "#include <stdint.h>",
             "#define VOICE_RATE %d" % rate, ""]
    for name, s in clips:
        lines.append("const int16_t voice_%s[%d] = {" % (name, len(s)))
        for i in range(0, len(s), 16):
            lines.append("  " + ",".join(str(v) for v in s[i:i + 16]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("struct VoiceClip { const int16_t *data; uint32_t len; };")
    lines.append("const VoiceClip voices[] = {")
    for name, s in clips:
        lines.append("  {voice_%s, %d}," % (name, len(s)))
    lines.append("};")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
